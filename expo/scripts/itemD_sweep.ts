// ─── cell definition ────────────────────────────────────────────────────────
type Tp1Mode = "R" | "PIP";
type Tp23Mode = "abs" | "scaled";
type LockFamily = "fracTP1" | "fracR";

interface LockSpec {
  id: string;
  family: LockFamily;
  /** ordered value within the family (fraction of TP1, or fraction of R) */
  value: number;
  cap: boolean;
  ladder: LadderOverride;
}

interface Cell {
  tp1Mode: Tp1Mode;
  tp1Value: number;
  lock: LockSpec;
  tp23: Tp23Mode;
}

