// ─── geometry rebuild ───────────────────────────────────────────────────────
const r1 = (x: number): number => Number(x.toFixed(1));

interface Geom {
  sig: TradingSignal;
  stop: number;
  degenerate: boolean;
}

function buildGeometry(p: ParsedSignal, cell: Cell): Geom {
  const stop = Math.abs(p.entry - p.sl);
  const isBuy = p.direction === "BUY";
  const sgn = isBuy ? 1 : -1;

  const oldTp1d = Math.abs(p.tp1 - p.entry);
  const oldTp2d = Math.abs(p.tp2 - p.entry);
  const oldTp3d = Math.abs(p.tp3 - p.entry);

  const newTp1d = cell.tp1Mode === "R" ? cell.tp1Value * stop : cell.tp1Value * PIP;

  let newTp2d: number;
  let newTp3d: number;
  if (cell.tp23 === "abs") {
    newTp2d = oldTp2d;
    newTp3d = oldTp3d;
  } else {
    const k = oldTp1d > 0 ? newTp1d / oldTp1d : 1;
    newTp2d = oldTp2d * k;
    newTp3d = oldTp3d * k;
  }

  const sig = toTradingSignal(p);
  sig.tp1 = r1(p.entry + sgn * newTp1d);
  sig.tp2 = r1(p.entry + sgn * newTp2d);
  sig.tp3 = r1(p.entry + sgn * newTp3d);
  return { sig, stop, degenerate: newTp1d >= newTp2d };
}

/** Reproduce the resolver's lock arithmetic to report where floor/cap bind. */
function lockBinding(sig: TradingSignal, spec: LockSpec): { floor: boolean; cap: boolean } {
  const stop = Math.abs(sig.entryPrice - sig.sl);
  const tp1d = Math.abs(sig.tp1 - sig.entryPrice);
  const minDelta = 5 * PIP;
  const base = spec.family === "fracTP1" ? tp1d * spec.value : stop * spec.value;
  const floored = Math.max(base, minDelta);
  const ceiling = spec.cap && tp1d > 0 ? tp1d * 0.9 : Number.POSITIVE_INFINITY;
  return { floor: floored > base, cap: floored > ceiling };
}

// ─── cell evaluation ────────────────────────────────────────────────────────
interface Ctx {
  sigs: ParsedSignal[];
  slices: OhlcBar[][];
  evalNowMs: number;
  baselineR: number[];
}

function evalCell(cell: Cell, ctx: Ctx): CellResult {
  const rs: number[] = [];
  const dirs: ("BUY" | "SELL")[] = [];
  let net = 0;
  let degenerate = 0;
  let floorBinds = 0;
  let capBinds = 0;

  for (let i = 0; i < ctx.sigs.length; i++) {
    const p = ctx.sigs[i];
    const g = buildGeometry(p, cell);
    if (g.degenerate) degenerate++;
    const b = lockBinding(g.sig, cell.lock);
    if (b.floor) floorBinds++;
    if (b.cap) capBinds++;

    const out = resolveSignalWithBars(g.sig, ctx.slices[i], {
      fromScratch: true,
      evalNowMs: ctx.evalNowMs,
      ladder: cell.lock.ladder,
    });
    const pnl = p.direction === "BUY" ? out.exitPrice - p.entry : p.entry - out.exitPrice;
    rs.push(pnl / g.stop);
    dirs.push(p.direction);
    net += pnl;
  }

  const agg = (sel: (i: number) => boolean) => {
    const v: number[] = [];
    for (let i = 0; i < rs.length; i++) if (sel(i)) v.push(rs[i]);
    const w = v.filter((x) => x > 0);
    const l = v.filter((x) => x < 0);
    const gw = w.reduce((a, b) => a + b, 0);
    const gl = Math.abs(l.reduce((a, b) => a + b, 0));
    return {
      n: v.length,
      wr: v.length ? (w.length / v.length) * 100 : 0,
      pf: gl > 0 ? gw / gl : Number.POSITIVE_INFINITY,
      ev: v.length ? v.reduce((a, b) => a + b, 0) / v.length : 0,
    };
  };

  const all = agg(() => true);
  const buy = agg((i) => dirs[i] === "BUY");
  const sell = agg((i) => dirs[i] === "SELL");

  let conversions = 0;
  let reversions = 0;
  for (let i = 0; i < rs.length; i++) {
    if (ctx.baselineR[i] < 0 && rs[i] > 0) conversions++;
    if (ctx.baselineR[i] > 0 && rs[i] < 0) reversions++;
  }

  return {
    cell,
    n: all.n,
    wr: all.wr,
    pf: all.pf,
    ev: all.ev,
    net,
    evBuy: buy.ev,
    evSell: sell.ev,
    wrBuy: buy.wr,
    wrSell: sell.wr,
    pfBuy: buy.pf,
    pfSell: sell.pf,
    nBuy: buy.n,
    nSell: sell.n,
    conversions,
    reversions,
    degenerate,
    floorBinds,
    capBinds,
    rs,
  };
}

// ─── stats ──────────────────────────────────────────────────────────────────
function mean(v: number[]): number {
  return v.reduce((a, b) => a + b, 0) / v.length;
}
function sd(v: number[]): number {
  const m = mean(v);
  return Math.sqrt(v.reduce((a, b) => a + (b - m) * (b - m), 0) / (v.length - 1));
}
/** Paired difference vs baseline: same signals, so pairing is valid and tighter. */
function pairedDelta(cellR: number[], baseR: number[]): { d: number; se: number; lo: number; hi: number } {
  const diffs = cellR.map((x, i) => x - baseR[i]);
  const d = mean(diffs);
  const se = sd(diffs) / Math.sqrt(diffs.length);
  return { d, se, lo: d - 1.96 * se, hi: d + 1.96 * se };
}

const sgn = (x: number): string => (x >= 0 ? "+" : "");
const pfs = (x: number): string => (Number.isFinite(x) ? x.toFixed(2) : "inf");

function cellLabel(c: Cell): string {
  const v = c.tp1Mode === "R" ? `${c.tp1Value.toFixed(2)}R` : `${c.tp1Value.toFixed(1)}p`;
  return `TP1=${v.padStart(6)} lock=${c.lock.id.padEnd(13)} tp23=${c.tp23.padEnd(6)}`;
}

// ─── MFE / MAE ──────────────────────────────────────────────────────────────
interface Excursion {
  index: number;
  dir: "BUY" | "SELL";
  status: string;
  mfe24: number;
  mae24: number;
  mfeRes: number;
  maeRes: number;
}

function excursions(ctx: Ctx, canon: Canon[]): Excursion[] {
  const byId = new Map(canon.map((c) => [c.p.id, c]));
  const out: Excursion[] = [];
  for (let i = 0; i < ctx.sigs.length; i++) {
    const p = ctx.sigs[i];
    const c = byId.get(p.id);
    if (!c) continue;
    const stop = Math.abs(p.entry - p.sl);
    const isBuy = p.direction === "BUY";
    const bars = ctx.slices[i];
    const horizon = p.generatedMs + 24 * 60 * 60 * 1000;
    const resEnd = c.resolvedAtBarTs ?? Number.POSITIVE_INFINITY;
    let mfe24 = 0;
    let mae24 = 0;
    let mfeRes = 0;
    let maeRes = 0;
    for (const b of bars) {
      const fav = isBuy ? b.high - p.entry : p.entry - b.low;
      const adv = isBuy ? p.entry - b.low : b.high - p.entry;
      if (b.timestamp <= horizon) {
        if (fav > mfe24) mfe24 = fav;
        if (adv > mae24) mae24 = adv;
      }
      if (b.timestamp <= resEnd) {
        if (fav > mfeRes) mfeRes = fav;
        if (adv > maeRes) maeRes = adv;
      }
      if (b.timestamp > horizon && b.timestamp > resEnd) break;
    }
    out.push({
      index: p.index,
      dir: p.direction,
      status: c.newStatus,
      mfe24: mfe24 / stop,
      mae24: mae24 / stop,
      mfeRes: mfeRes / stop,
      maeRes: maeRes / stop,
    });
  }
  return out;
}

function quantiles(v: number[]): { p10: number; p25: number; p50: number; p75: number; p90: number } {
  const s = [...v].sort((a, b) => a - b);
  const q = (f: number): number => s[Math.min(s.length - 1, Math.floor(f * s.length))];
  return { p10: q(0.1), p25: q(0.25), p50: q(0.5), p75: q(0.75), p90: q(0.9) };
}

