/**
 * ITEM 57 — REAL-BAR REPLAY HARNESS.
 *
 * The standing instrument for any future "how many signals before vs after?"
 * question. Replays the REAL engine over REAL `gold_m1_bars` via the existing
 * `__injectBarSeriesForTestOnly` hook.
 *
 * WHY THIS EXISTS. `runSignalSimulation.ts` was disqualified in Item 53: it drives
 * the engine from `generateSyntheticPrice()` with base 3034.5 while live gold is
 * ~4250. Every price-scale-dependent gate (zone width, bounce threshold, the
 * absolute-dollar ATR regime constants) is unmeasurable on that tape. This harness
 * replaces the synthetic generator with the real one, and nothing else.
 *
 * HOW IT WORKS.
 *   1. `buildSandboxEngine()` transforms `services/signalEngine.ts` into a
 *      Node-runnable module: the `react-native` import (Flow-typed, unparseable by
 *      bun/node) and the AsyncStorage / trpc / learning-store imports are replaced
 *      with in-memory stubs. This is the same transform the __sandbox_item44__ /
 *      __sandbox_item45__ copies used, but GENERATED from the live file at run time
 *      rather than hand-copied — so the harness can never silently drift from the
 *      shipped engine the way a stale hand-copy would.
 *   2. Real M1 bars are paged from Supabase via the anon key (DATA-SOURCE RULE).
 *   3. Bars are injected with `__injectBarSeriesForTestOnly`, then the engine is
 *      stepped forward bar by bar with the real close as the external price.
 *   4. Emissions and rejection reasons are captured off the engine's own console
 *      output and template-aggregated (variable numbers collapsed to `<N>`) so the
 *      breakdown is stable across runs.
 *
 * USAGE:
 *   bun scripts/item57_realbar_replay_harness.ts            # replay, print breakdown
 *   bun scripts/item57_realbar_replay_harness.ts --label X  # tag the run for A/B
 *
 * READ-ONLY against Supabase.
 */

import { createClient } from '@supabase/supabase-js';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { join } from 'node:path';

interface Bar {
  timestamp: number;
  open: number;
  high: number;
  low: number;
  close: number;
}

const loadEnv = (): Record<string, string> => {
  const env: Record<string, string> = {};
  try {
    for (const line of readFileSync('.env', 'utf-8').split('\n')) {
      const trimmed = line.trim();
      if (!trimmed || trimmed.startsWith('#')) continue;
      const eq = trimmed.indexOf('=');
      if (eq < 0) continue;
      env[trimmed.slice(0, eq)] = trimmed.slice(eq + 1).replace(/^["']|["']$/g, '');
    }
  } catch {
    // fall through
  }
  return env;
};

