/**
 * Rewrite the live engine into a Node-runnable module.
 * Only IMPORTS are stubbed. No engine logic is altered — that is the whole point:
 * the harness must measure the shipped engine, not a fork of it.
 */
function buildSandboxEngine(): string {
  const src = readFileSync('services/signalEngine.ts', 'utf-8');
  const lines = src.split('\n');

  // ITEM 84 — `--tier0-dark` stubs the TIER_0 zone read so the engine runs with NO
  // server zones. `fetchTier0SRZones` is otherwise NOT stubbed: the replay reads the
  // live `sr_zones_v1` table, which is why the armed arm is a genuine armed arm.
  // Item 84 asks whether the FIXED 0.55 conviction threshold is materially stricter
  // when the zone layer works than when it is dark — i.e. whether the engine emits
  // MORE when its zone layer is broken. That requires a dark arm that is dark for
  // one reason only.
  const tier0Dark = process.argv.includes('--tier0-dark');

  const stubs = [
    '// AUTO-GENERATED by item57_realbar_replay_harness.ts. Do not edit.',
    '// Imports are stubbed for Node; ALL engine logic below is byte-identical to',
    '// services/signalEngine.ts as shipped.',
    'const sandboxStorage = new Map<string, string>();',
    'const AsyncStorage = {',
    '  async getItem(key: string): Promise<string | null> { return sandboxStorage.get(key) ?? null; },',
    '  async setItem(key: string, value: string): Promise<void> { sandboxStorage.set(key, value); },',
    '  async removeItem(key: string): Promise<void> { sandboxStorage.delete(key); },',
    '};',
    'const Platform = { OS: "web" as const };',
    'const trpcClient = {} as never;',
    'async function fetchHistoricalData(): Promise<never[]> { return []; }',
    'async function appendOutcomeToStore(): Promise<void> {}',
    'async function getAllOutcomesFromStore(): Promise<unknown[]> { return []; }',
    'async function getOutcomeCountFromStore(): Promise<number> { return 0; }',
    'async function pruneOutcomeStoreToCap(): Promise<void> {}',
    'async function migrateLegacyOutcomesIfEmpty(): Promise<number> { return 0; }',
    'async function pushOutcomesToRemote(): Promise<{ upserted: number; queued: number; failed: number; failureDetail: string | null }> { return { upserted: 0, queued: 0, failed: 0, failureDetail: null }; }',
    'async function hydrateLearningStoreFromRemote(): Promise<unknown> { return { available: false }; }',
    'function getLearningCorpusStats(): { hydrateUnavailableCount: number } { return { hydrateUnavailableCount: 0 }; }',
    'type StoredTradeOutcome = Record<string, unknown>;',
    'async function appendDiagnosticEvent(): Promise<void> {}',
    'async function pushShadowSellRecord(): Promise<void> {}',
    'async function pushEmittedSignalRecord(): Promise<void> {}',
    'type ShadowSellRecord = Record<string, unknown>;',
    ...(tier0Dark
      ? [
          '// ITEM 84 dark arm: TIER_0 server zones forced unavailable.',
          'async function fetchTier0SRZones(): Promise<null> { return null; }',
          'function recordTier0FallbackUse(): void {}',
        ]
      : []),
    '',
    '// A11: seed production model weights so getFeatureModulation returns the LIVE',
    '// value (rsi_weight=-1.0 -> modulation=0) instead of the cold-start 1.0.',
    'sandboxStorage.set("model_weights_v1", JSON.stringify({ weights: [["rsi_weight",-1.0],["sentiment_weight",-0.473823],["atr_weight",0.225086],["timeWindow_weight",-0.09845],["volume_weight",0.082048],["dxy_weight",0.0]], lastTrainingTime: Date.parse("2026-08-11T12:06:34Z"), corpusSizeAtTraining: 53, hydrateUnavailableAtTraining: 0 }));',
    '',
  ];

  // Drop the import statements that pull in React Native / storage / network.
  const dropPrefixes = [
    ...(tier0Dark ? ['import { fetchTier0SRZones'] : []),
    'import AsyncStorage from',
    'import { Platform } from "react-native"',
    'import { fetchHistoricalData, trpcClient } from',
    'import { appendOutcome as appendOutcomeToStore',
    'import { appendDiagnosticEvent } from',
    'import { pushShadowSellRecord',
    'import { pushEmittedSignalRecord } from',
  ];

  const kept: string[] = [];
  let i = 0;
  while (i < lines.length) {
    const line = lines[i];
    const matched = dropPrefixes.some((p) => line.startsWith(p));
    if (matched) {
      // Consume the whole (possibly multi-line) import statement.
      let stmt = line;
      while (!stmt.includes('";') && !stmt.trimEnd().endsWith('"') && i + 1 < lines.length) {
        i += 1;
        stmt += lines[i];
      }
      i += 1;
      continue;
    }
    kept.push(line);
    i += 1;
  }

  // Rewrite the `@/` alias to relative paths so Node resolves them.
  const body = kept.join('\n').replace(/from "@\//g, 'from "../../').replace(/from '@\//g, "from '../../");

  return `${stubs.join('\n')}\n${body}\n`;
}

const pct = (n: number, d: number): string => (d === 0 ? 'n/a' : `${((n / d) * 100).toFixed(1)}%`);

/** Collapse variable numbers so rejection reasons aggregate into stable templates. */
const templatize = (msg: string): string =>
  msg
    .replace(/-?\d+\.\d+/g, '<N>')
    .replace(/\b\d+\b/g, '<N>')
    .replace(/\s+/g, ' ')
    .trim()
    .slice(0, 120);

